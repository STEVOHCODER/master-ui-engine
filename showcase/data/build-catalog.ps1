# Rebuild the visual lab's catalog mirror and re-stamp the metadata header in
# every preview. showcase/data/component-catalog.json is the single source of
# truth: edit it, then run this.
#
#   powershell -File showcase/data/build-catalog.ps1
#
$ErrorActionPreference = 'Stop'
# repo root = two levels above showcase/data
$root = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
$catalogPath = Join-Path $PSScriptRoot 'component-catalog.json'
$utf8 = New-Object System.Text.UTF8Encoding($false)

$raw = Get-Content $catalogPath -Raw
$catalog = $raw | ConvertFrom-Json

# --- 1. catalog.js: a verbatim mirror the lab can load from file:// ---------
$js = "// GENERATED by showcase/data/build-catalog.ps1 - do not edit by hand.`n" +
      "// Single source of truth: showcase/data/component-catalog.json`n" +
      "window.MUE_CATALOG = " + $raw.TrimEnd() + ";`n"
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'catalog.js'), $js, $utf8)

# --- 2. metadata headers ----------------------------------------------------
# One single HTML comment. Two adjacent comments would leave the field lines as
# raw text inside <head>, and the parser relocates them (and the rest of the
# document) into <body>.
$open  = '<!-- BEGIN MUE:META'
$close = 'END MUE:META -->'
$stripOld = [regex]'(?s)<!-- MUE:META -->.*?(?:<!-- /MUE:META -->\r?\n|(?=<title>))'
$strip = [regex]'(?s)<!-- BEGIN MUE:META.*?END MUE:META -->\r?\n?'

# The only thing that has to be neutralised inside an HTML comment is the
# sequence that would close it. A blanket "--" -> "-" collapse looks equivalent
# and silently rewrites every CSS custom property named in a field, turning
# --motion-lift into -motion-lift.
function Safe([string]$value) { if ($null -eq $value) { '' } else { $value -replace '-->', '- >' } }

function Kind($group) {
  switch ($group) {
    'Components' { 'COMPONENT' }
    'Templates'  { 'TEMPLATE' }
    default      { 'EXAMPLE' }
  }
}

# The catalog owns identity (id, name, group, category) and the fields it
# carries. Everything describing the *shared layer* — which files the head links,
# which #region block defines the markup, where motion comes from — is read back
# out of the file itself, because that is where the truth is and the catalog has
# no idea until the conversion happens.
function ParseExisting([string]$text) {
  $map = @{}
  $m = [regex]::Match($text, '(?s)<!-- BEGIN MUE:META.*?END MUE:META -->')
  if (-not $m.Success) { return $map }
  foreach ($line in ($m.Value -split "`r?`n")) {
    if ($line -match '^\s{2}([A-Z_]+):\s*(.*)$') { $map[$matches[1]] = $matches[2].Trim() }
  }
  return $map
}

$stamped = 0
$missing = @()
$unlinked = @()
$noSheet = @()

foreach ($item in $catalog.items) {
  $file = Join-Path $root ($item.path -replace '/', [IO.Path]::DirectorySeparatorChar)
  if (-not (Test-Path $file)) { $missing += $item.path; continue }
  $text = [IO.File]::ReadAllText($file)
  $titleAt = $text.IndexOf('<title>')
  if ($titleAt -lt 0) { $missing += ($item.path + ' (no <title>)'); continue }
  if ($text -notmatch 'design-tokens/engine\.css') { $unlinked += $item.path }

  # Only the head counts: a code panel quotes the very hrefs we are probing for.
  $headEnd = $text.IndexOf('</head>')
  $head = if ($headEnd -gt 0) { $text.Substring(0, $headEnd) } else { $text.Substring(0, $titleAt) }
  $hasSheet = $head -match 'styles/components\.css'
  $hasScript = $head -match 'styles/mue\.js'
  if (-not $hasSheet) { $noSheet += $item.path }

  $deps = @(
    if ($hasSheet) { 'design-tokens/engine.css', 'styles/components.css' } else { 'design-tokens/engine.css' }
    if ($hasScript) { 'styles/mue.js' }
  ) -join ', '
  $depsText = if ($hasScript) {
    "$deps (all linked in this head)"
  } elseif ($hasSheet) {
    "$deps (linked in this head); the page adds no JS"
  } else {
    "$deps (linked in this file head); no web fonts, CDNs or JS libraries, and no shared sheet yet"
  }

  $existing = ParseExisting $text
  # Identity comes from the catalog. Description stays with whoever wrote the
  # file: a converted preview states its variant list, its breakpoint behaviour
  # and which widths it was audited at in more detail than the catalog's
  # generated fields, and re-deriving them here would flatten that prose.
  function Pick($key, $fallback) {
    if ($existing.ContainsKey($key) -and $existing[$key]) { return $existing[$key] }
    return $fallback
  }
  $lines = @(
    $open,
    ('  {0}: {1}' -f (Kind $item.group), (Safe $item.name)),
    "  ID: $($item.id)",
    "  GROUP: $($item.group)",
    "  CATEGORY: $($item.category)",
    '  FRAMEWORK: vanilla (HTML/CSS/JS, no build step)',
    '  DESIGN_SYSTEM: MASTER-UI-ENGINE tokens',
    "  DEPENDENCIES: $depsText"
  )
  if ($existing.ContainsKey('SHEET')) { $lines += '  SHEET: ' + (Safe $existing['SHEET']) }
  $theme = if ($hasScript) { 'light + dark (html.dark, persisted and synced by styles/mue.js)' } else { $item.theming }
  $lines += "  THEME: $(Safe (Pick 'THEME' $theme))"
  $variantText = if ($item.variants -and $item.variants.Count) { $item.variants -join ', ' } else { '' }
  $variants = Pick 'VARIANTS' $variantText
  if ($variants) { $lines += '  VARIANTS: ' + (Safe $variants) }
  if ($existing.ContainsKey('MOTION')) { $lines += '  MOTION: ' + (Safe $existing['MOTION']) }
  $responsive = Pick 'RESPONSIVE' $(if ($item.breakpoints -and $item.breakpoints.Count) {
    'reflows at ' + ($item.breakpoints -join ', ')
  } else {
    'fluid layout, no breakpoint needed'
  })
  $verified = Pick 'VERIFIED' $item.verified
  $lines += @(
    "  RESPONSIVE: $(Safe $responsive)",
    "  VERIFIED: $(Safe $verified)",
    "  CATALOG: showcase/data/component-catalog.json#$($item.id)",
    '  LICENSE: MIT',
    '  ATTRIBUTION: MASTER-UI-ENGINE contributors',
    $close
  )

  $block = ($lines -join "`n") + "`n"
  $text = $strip.Replace($stripOld.Replace($text, ''), '')
  $titleAt = $text.IndexOf('<title>')
  [IO.File]::WriteAllText($file, $text.Substring(0, $titleAt) + $block + $text.Substring($titleAt), $utf8)
  $stamped++
}

# --- 3. report --------------------------------------------------------------
Write-Host "catalog.js written, $stamped previews re-stamped"
if ($missing.Count)  { Write-Warning ("missing files: " + ($missing -join ', ')) }
if ($unlinked.Count) { Write-Warning ("previews not linking engine.css: " + ($unlinked -join ', ')) }
if ($noSheet.Count)  { Write-Host ("previews still self-contained (no shared sheet): " + ($noSheet -join ', ')) }
if ($missing.Count -or $unlinked.Count) { exit 1 }
